package javapractices;

public class DemoProtected {

	public int a = 20;
	int b = 30;
	private int c = 40;
	protected int d = 50;

	public void add() {
		System.out.println(10 + 20);
	}

	void sub() {
		System.out.println(20 - 10);
	}

	private void mul() {
		System.out.println(20 * 10);
	}

	protected void div() {
		System.out.println(20 / 10);
	}

}
